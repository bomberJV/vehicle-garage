import {TAU,metal,steel,dark,gold,copper,turn,sleeve,cyl,part,study,origin,z} from './mechanism-shapes.js';
const src={label:'NGK · spark plug construction',url:'https://ngksparkplugs.com/wp-content/uploads/2020/10/QA-SparkPlug-.pdf'};
const porcelain='#e6e8dc',glass='#b4a28a';
const exposed={start:.18*Math.PI,sweep:1.38*Math.PI,n:28};
function shell(r) {
  turn(r,origin,z,[[.36,.21],[.36,.32],[.75,.32],[.78,.39],[.83,.39],[.83,.25],[.76,.20],[.36,.21]],steel,exposed);
  turn(r,origin,z,[[.83,.25],[.83,.46],[1.03,.46],[1.06,.35],[1.14,.34],[1.14,.245],[.83,.25]],metal,{...exposed,n:5});
  // A helical crest follows the circumference and terminates at the longitudinal cut.
  const pitch=.055,turns=7;
  for(let i=0;i<28*turns;i++){
    const a=TAU*i/28,b=TAU*(i+1)/28;
    if((a%TAU)<exposed.start||(b%TAU)>exposed.start+exposed.sweep)continue;
    const profile=(t)=>[[.318,-.012],[.348,0],[.318,.015]].map(([rad,dz])=>[Math.cos(t)*rad,Math.sin(t)*rad,.38+pitch*t/TAU+dz]);
    const A=profile(a),B=profile(b);
    for(let j=0;j<2;j++)r.polygon([A[j],A[j+1],B[j+1],B[j]],j?metal:dark,false);
  }
}
function ceramic(r){
  const profile=[[.27,.071],[.42,.12],[.72,.18],[.78,.219],[1.14,.241],[1.20,.28],[1.55,.24]];
  for(let i=0;i<5;i++){const h=1.56+i*.088;profile.push([h,.233],[h+.02,.257],[h+.052,.257],[h+.075,.232]);}
  profile.push([2.015,.206],[2.12,.177],[2.12,.081],[.34,.06],[.27,.071]);
  turn(r,origin,z,profile,porcelain,exposed);
}
function center(r){
  turn(r,origin,z,[[.24,.024],[.24,.046],[.56,.055],[.94,.066],[.94,.031],[.46,.026],[.24,.024]],metal,exposed);
  cyl(r,origin,z,.39,.95,.027,copper,16);
}
